# ---------- 1. 试试 print() 打印输出 ----------
# print() 可以把括号里的内容显示在屏幕上
# 字符串（文字）要用引号括起来，单引号双引号都可以

print("Hello, Python!")  # 这是我的第一行代码 🎉
print('你好，世界！')


# ---------- 2. 变量 —— 给数据起个名字 ----------
# 用 = 把右边的值赋给左边的变量名（注意：= 不是数学里的"等于"）

name = "小明"          # 字符串
age = 18               # 整数
height = 1.75          # 浮点数（小数）
is_student = True      # 布尔值（True 或 False）

print(name)
print(age)


# ---------- 3. 简单的数学运算 ----------
# + 加  - 减  * 乘  / 除  // 整除  % 取余  ** 幂

x = 10
y = 3

print(x + y)    # 13
print(x - y)    # 7
print(x * y)    # 30
print(x / y)    # 3.333...
print(x // y)   # 3（整除，只留整数部分）
print(x % y)    # 1（10 除以 3 余 1）
print(x ** y)   # 1000（10 的 3 次方）


# ---------- 4. f-string 格式化输出（超好用！） ----------
# 在字符串前加 f，花括号里直接放变量

print(f"我叫{name}，今年{age}岁，身高{height}米。")


